"""aside-relay configuration.

Resolution order (first hit wins):
  1. real environment variables (ASIDE_RELAY_*)
  2. env file:  ~/.aside-relay/env  then  <repo>/.env   (KEY=VALUE lines)
  3. built-in defaults (never personal)

Run `python3 scripts/setup.py` for a guided setup, or write the env file by hand —
see README for every key.
"""
from __future__ import annotations

import os
from pathlib import Path

HOME = Path.home()
APP_NAME = "aside-relay"
BASE_DIR = Path(__file__).resolve().parent


# --- tiny env-file loader (no external deps) ---------------------------
def _load_env_files() -> None:
    for f in (HOME / ".aside-relay/env", BASE_DIR / ".env"):
        try:
            for line in f.read_text().splitlines():
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                k, v = k.strip(), v.strip().strip('"').strip("'")
                if k and k not in os.environ:      # real env always wins
                    os.environ[k] = v
        except OSError:
            pass


_load_env_files()
_env = os.environ.get

